import {test} from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const get=file=>readFileSync(new URL("../"+file,import.meta.url),"utf8");
test("native player is scoped to a fixed TLS Jellyfin origin",()=>{
  const rust=get("src-tauri/src/native_stream.rs");
  const app=get("src-tauri/src/main.rs");
  const api=get("frontend/src/api.ts");
  assert.match(rust, /const JELLYFIN_ORIGIN: &str = "https:\/\/cocojellyfin\.duckdns\.org:38443";/);
  assert.match(rust, /reqwest::redirect::Policy::none\(\)/);
  assert.match(rust, /const CHUNK: u64 = 2 \* 1024 \* 1024/);
  assert.match(rust, /\.header\(header::RANGE, range\)/);
  assert.match(rust, /request\.uri\(\)\.query\(\)\.is_some\(\)/);
  assert.match(rust, /expires: Instant/);
  assert.match(rust, /Uuid::new_v4/);
  assert.match(rust, /map\.clear\(\)/);
  assert.doesNotMatch(rust, /api_key|header\(header::LOCATION/);
  assert.match(app, /register_asynchronous_uri_scheme_protocol/);
  assert.match(app, /"vyneo-media"/);
  assert.match(app, /stop_all_native_streams/);
  assert.match(api, /SESSION_CHANGED/);
  assert.match(api, /validateStreamTicket\(raw\)/);
});
test("HLS uses local capability assets with pinned Jellyfin origin",()=>{
  const hls=get("src-tauri/src/native_hls.rs");
  const native=get("src-tauri/src/native_stream.rs");
  assert.match(hls,/const UPSTREAM: &str = "https:\/\/cocojellyfin\.duckdns\.org:38443"/);
  assert.match(hls,/validated_playlist_url/);
  assert.match(hls,/master\.m3u8/);
  assert.match(hls,/videocodec/);
  assert.match(hls,/audiocodec/);
  assert.match(hls,/negotiated_hls/);
  assert.match(hls,/MAX_PLAYLIST: usize = 512 \* 1024/);
  assert.match(hls,/MAX_SEGMENT: usize = 16 \* 1024 \* 1024/);
  assert.match(hls,/access_token/);
  assert.match(hls,/api_key/);
  assert.match(hls,/sanitized_upstream/);
  assert.match(hls,/rewrite_playlist/);
  assert.match(hls,/StreamKind::Hls/);
  assert.match(native,/StreamKind::Hls/);
  assert.match(native,/"hls" => StreamKind::Hls/);
  const page=get("frontend/src/MediaDetails.svelte");
  assert.match(page,/import\("hls.js"\)/);
  assert.match(page,/selectJellyfinHls\(\{/);
  assert.match(page,/negotiatePlaybackInfo\(target\.id,\s*selectedAudioIndex/);
  assert.match(page,/AudioStreamIndex|audioStreamIndex/);
  assert.match(page,/getSubtitleVtt/);
  assert.match(page,/negotiation\.hlsPaths\[source\.id\]/);
  assert.match(page,/if\(!videoElement\)/);
  assert.match(page,/stopStream\(true\)/);
  assert.match(page,/player\?\.destroy\(\)/);
});
test("video CSP allows only Tauri custom media and no token-bearing URLs",()=>{
  const html=get("frontend/index.html");
  assert.match(html, /media-src 'self' blob: http:\/\/vyneo-media\.localhost vyneo-media:/);
  assert.match(html, /worker-src 'self' blob:/);
  assert.match(html, /connect-src[^;]+http:\/\/vyneo-media\.localhost vyneo-media:/);
  assert.match(html,/connect-src 'self' https:\/\/cocojellyfin\.duckdns\.org:38443/);
  assert.doesNotMatch(html,/upgrade-insecure-requests/);
  const ui=get("frontend/src/MediaDetails.svelte");
  // Direct MP4 remains selectable by codec, but explicit audio switching
  // only permits the server-negotiated HLS path with the selected source.
  assert.match(ui, /selectDirectMp4\(\{\.\.\.probe,sources:candidates\}\)/);
  assert.match(ui, /selectedAudioIndex===null/);
  assert.match(ui, /negotiation\.hlsPaths\[source\.id\]/);
  assert.match(ui, /getSubtitleVtt/);
  assert.match(ui, /URL\.revokeObjectURL\(old\)/);
  assert.match(ui, /src=\{streamKind==="direct"\?streamTicket\.url:undefined\}/);
  assert.match(ui, /onerror=/);
  assert.match(ui, /stopStream\(\)/);
  assert.doesNotMatch(ui,/\/Videos\//);
});
