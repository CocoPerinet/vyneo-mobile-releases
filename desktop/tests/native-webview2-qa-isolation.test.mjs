import {test} from "node:test";
import {strict as assert} from "node:assert";
import {readFileSync,statSync} from "node:fs";
const read=file=>readFileSync(new URL("../"+file,import.meta.url),"utf8");
test("synthetic WebView2 media QA is compile-time isolated from production",()=>{
  const cargo=read("src-tauri/Cargo.toml");
  const entry=read("src-tauri/src/main.rs");
  const streamer=read("src-tauri/src/native_hls.rs");
  const ticketState=read("src-tauri/src/native_stream.rs");
  const qa=read("src-tauri/src/native_e2e_qa.rs");
  const cfg=JSON.parse(read("src-tauri/tauri.jellyfin-qa.conf.json"));
  const stable=JSON.parse(read("src-tauri/tauri.conf.json"));
  const runner=read("qa/native-webview2-smoke.mjs");
  const fixtureJs=read("qa/native-webview2/test.template.js");
  assert.match(cargo,/\[features\]\s*#[^\n]*\nnative-e2e-qa = \[\]/);
  assert.doesNotMatch(cargo,/^default = \[[^\]]*native-e2e-qa/m);
  assert.match(entry,/\#\[cfg\(feature="native-e2e-qa"\)\]\s*mod native_e2e_qa;/);
  assert.match(entry,/\.visible\(!cfg!\(feature="native-e2e-qa"\)\)/);
  assert.match(entry,/if !cfg!\(feature="native-e2e-qa"\)/);
  assert.match(streamer,/\#\[cfg\(feature="native-e2e-qa"\)\]/);
  assert.match(streamer,/crate::native_e2e_qa::is_fixture\(&grant\)/);
  assert.match(qa,/include_bytes!\(\s*"\.\.\/\.\.\/qa\/fixtures\/hls\/segment000.ts"/);
  assert.match(qa,/is_fixture\(grant:&StreamGrant\)/);
  assert.match(runner,/--debug --no-bundle --features native-e2e-qa/);
  assert.match(runner,/windowsHide:true/);
  assert.match(runner,/QA_ZERO_INSTALLER_ZERO_REAL_CREDENTIALS/);
  assert.match(runner,/m.audioRmsPeak>=0.008/);
  assert.match(fixtureJs,/new window.AudioContext\(\)/);
  assert.match(fixtureJs,/createMediaElementSource\(video\)/);
  assert.match(fixtureJs,/zeroGain.gain.value=0/);
  assert.match(fixtureJs,/zeroGain.connect\(context.destination\)/);
  assert.match(fixtureJs,/invoke\("check_signed_update_now"\)/);
  assert.match(fixtureJs,/UPDATE_DISABLED_IN_QA/);
  assert.match(runner,/m.updaterQaGuarded/);
  assert.match(fixtureJs,/await report\("PASS",metrics\)/);
  assert.match(runner,/cleanupOrphanedQaTasks\(\)/);
  assert.match(runner,/New-ScheduledTaskSettingsSet -ExecutionTimeLimit/);
  assert.match(runner,/New-TimeSpan -Minutes 2/);
  assert.match(ticketState,/cfg\(feature="native-e2e-qa"\)/);
  assert.match(ticketState,/if quit_qa \{ app.exit\(0\); \}/);
  assert.notEqual(cfg.identifier,stable.identifier);
  assert.equal(cfg.identifier,"fr.visyren.vyneo.desktop.jellyfinqa");
  assert.equal(cfg.build.frontendDist,"../qa-native-dist");
  assert.equal(stable.build.frontendDist,"../frontend/dist");
  assert.equal(stable.bundle.createUpdaterArtifacts,false);
  assert(!read("frontend/index.html").includes("qa-native-dist"));
  assert(statSync(new URL("../qa/fixtures/hls/segment000.ts",import.meta.url)).size>50_000);
});
